//! The RGB-to-spectrum tables: for each colour space, the coefficients of
//! the [`RGBSigmoidPolynomial`] of every RGB on a grid, interpolated between
//! (PBR 4e §4.6.6, Jakob and Hanika 2019).
//!
//! The build script optimises them with pbrt-v4's `rgb2spec_opt`
//! (`build/rgb2spec.rs`, ADR 0022) and writes them as little-endian `f32`,
//! included here as bytes and read with `f32::from_le_bytes`.

use umbra_math::{find_interval, lerp};

use crate::color::{RGB, RGBSigmoidPolynomial};

/// The table resolution along each axis.
///
/// pbrt-v4 `RGBToSpectrumTable::res`.
const RES: usize = 64;

/// The number of `f32` in a table: the `z` nodes, then three coefficients
/// for each of the `3 × RES³` cells.
const LEN: usize = RES + 3 * RES * RES * RES * 3;

/// The sRGB table generated by the build script.
static SRGB_BYTES: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/srgb_to_spectrum.bin"));

/// The sRGB table.
///
/// pbrt-v4 `RGBToSpectrumTable::sRGB`.
pub(crate) static SRGB: RGBToSpectrumTable = RGBToSpectrumTable::from_le_bytes(SRGB_BYTES);

/// A colour space's RGB-to-spectrum table: for each of the three RGB
/// components that can be the largest, the [`RGBSigmoidPolynomial`]
/// coefficients over a `RES³` grid indexed by that largest value `z`, at
/// the `z` nodes, and by the other two components, in order after it,
/// divided by `z`.
///
/// PBR 4e §4.6.6, pbrt-v4 `RGBToSpectrumTable`.
#[derive(Debug)]
pub(crate) struct RGBToSpectrumTable {
    /// The `RES` values of `z` the grid is spaced at.
    z_nodes: &'static [[u8; 4]],
    /// The coefficients, `[maxc][z][y][x][c]`.
    coeffs: &'static [[u8; 4]],
}

impl RGBToSpectrumTable {
    /// The table in `bytes`, as the build script writes it.
    ///
    /// # Panics
    ///
    /// At compile time, if `bytes` is not a table's length.
    const fn from_le_bytes(bytes: &'static [u8]) -> Self {
        let (words, rest) = bytes.as_chunks::<4>();
        assert!(
            rest.is_empty() && words.len() == LEN,
            "the build script writes a table of LEN f32"
        );
        let (z_nodes, coeffs) = words.split_at(RES);
        Self { z_nodes, coeffs }
    }

    /// `z` node `i`.
    fn z_node(&self, i: usize) -> f32 {
        f32::from_le_bytes(self.z_nodes[i])
    }

    /// Coefficient `c` of cell `(maxc, z, y, x)`.
    fn coefficient(&self, [maxc, z, y, x]: [usize; 4], c: usize) -> f32 {
        f32::from_le_bytes(self.coeffs[(((maxc * RES + z) * RES + y) * RES + x) * 3 + c])
    }

    /// The sigmoid polynomial of `rgb`, each component in `[0, 1]`: exact
    /// for a grey, trilinearly interpolated between the grid cells around
    /// `rgb` otherwise.
    ///
    /// PBR 4e §4.6.6, pbrt-v4 `RGBToSpectrumTable::operator()`.
    pub(crate) fn lookup(&self, rgb: RGB) -> RGBSigmoidPolynomial {
        debug_assert!(
            [rgb.r, rgb.g, rgb.b]
                .iter()
                .all(|v| (0.0..=1.0).contains(v)),
            "RGB-to-spectrum table lookup of {rgb:?}, outside [0, 1]"
        );
        #[expect(clippy::float_cmp, reason = "pbrt-v4's exact test for a grey")]
        if rgb.r == rgb.g && rgb.g == rgb.b {
            return RGBSigmoidPolynomial::new(
                0.0,
                0.0,
                (rgb.r - 0.5) / umbra_math::sqrt(rgb.r * (1.0 - rgb.r)),
            );
        }

        // The largest component, and the others in order after it relative
        // to it, scaled to the grid.
        let maxc = max_component(rgb);
        let z = rgb[maxc];
        #[expect(clippy::cast_precision_loss, reason = "RES − 1 is 63")]
        let scale = (RES - 1) as f32;
        let x = rgb[(maxc + 1) % 3] * scale / z;
        let y = rgb[(maxc + 2) % 3] * scale / z;

        // The cell and the offsets in it.
        let xi = grid_index(x);
        let yi = grid_index(y);
        let zi = find_interval(RES, |i| self.z_node(i) < z);
        #[expect(clippy::cast_precision_loss, reason = "a grid index below 63")]
        let (dx, dy) = (x - xi as f32, y - yi as f32);
        let dz = (z - self.z_node(zi)) / (self.z_node(zi + 1) - self.z_node(zi));

        let [c0, c1, c2] = [0, 1, 2].map(|c| self.trilerp([maxc, zi, yi, xi], [dx, dy, dz], c));
        RGBSigmoidPolynomial::new(c0, c1, c2)
    }

    /// Coefficient `c` trilinearly interpolated at `(dx, dy, dz)` in the
    /// cell from `(maxc, z, y, x)`, in pbrt-v4's order: along x, then y,
    /// then z.
    fn trilerp(&self, [maxc, z, y, x]: [usize; 4], [dx, dy, dz]: [f32; 3], c: usize) -> f32 {
        let co = |ox, oy, oz| self.coefficient([maxc, z + oz, y + oy, x + ox], c);
        lerp(
            dz,
            lerp(
                dy,
                lerp(dx, co(0, 0, 0), co(1, 0, 0)),
                lerp(dx, co(0, 1, 0), co(1, 1, 0)),
            ),
            lerp(
                dy,
                lerp(dx, co(0, 0, 1), co(1, 0, 1)),
                lerp(dx, co(0, 1, 1), co(1, 1, 1)),
            ),
        )
    }
}

/// The index of the largest component of `rgb`, the last of equals:
/// pbrt-v4's `maxc`.
fn max_component(rgb: RGB) -> usize {
    match (rgb.r > rgb.g, rgb.r > rgb.b, rgb.g > rgb.b) {
        (true, true, _) => 0,
        (false, _, true) => 1,
        (true, false, _) | (false, _, false) => 2,
    }
}

/// The grid cell of `v` in `[0, RES − 1]`: pbrt-v4's `std::min((int)v,
/// res - 2)`.
fn grid_index(v: f32) -> usize {
    #[expect(
        clippy::cast_possible_truncation,
        clippy::cast_sign_loss,
        reason = "C++ `(int)v` of a value in [0, 63]"
    )]
    let i = v as usize;
    i.min(RES - 2)
}
