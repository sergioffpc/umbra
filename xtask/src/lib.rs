//! The book-citation check (QS-4).

mod citation;
mod workspace;

use std::collections::BTreeMap;
use std::fmt;
use std::path::{Path, PathBuf};

use citation::Reference;
pub use workspace::{CORE_CRATES, Error};

/// One Rust source file of a core crate, with the module path it defines.
#[derive(Debug)]
pub struct Source {
    path: PathBuf,
    module: String,
    text: String,
}

impl Source {
    /// A source file at `path` (relative to the repository root) that defines
    /// the module `module` (for example `umbra_math::vector`).
    pub fn new(
        path: impl Into<PathBuf>,
        module: impl Into<String>,
        text: impl Into<String>,
    ) -> Self {
        Self {
            path: path.into(),
            module: module.into(),
            text: text.into(),
        }
    }
}

impl fmt::Display for Missing {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::SectionAndSymbol => {
                "a book section (`PBR 4e §x.y`) and a pbrt-v4 symbol (``pbrt-v4 `Symbol` ``)"
            }
            Self::Section => "a book section (`PBR 4e §x.y`)",
            Self::Symbol => "a pbrt-v4 symbol (``pbrt-v4 `Symbol` ``)",
        })
    }
}

/// What an item's doc comment lacks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Missing {
    /// Neither a book section nor a pbrt-v4 symbol.
    SectionAndSymbol,
    /// A book section (`PBR 4e §x.y`).
    Section,
    /// A pbrt-v4 symbol (``pbrt-v4 `Symbol` ``).
    Symbol,
}

impl fmt::Display for Violation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{}:{}: `{}` does not cite {}; cite it, or write `Not in pbrt-v4: <reason>`",
            self.path.display(),
            self.line,
            self.item,
            self.missing
        )
    }
}

/// An item that must cite the book but does not.
#[derive(Debug)]
pub struct Violation {
    path: PathBuf,
    line: usize,
    item: String,
    missing: Missing,
}

impl Violation {
    /// The file that defines the item, relative to the repository root.
    #[must_use]
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// The line of the item's name.
    #[must_use]
    pub fn line(&self) -> usize {
        self.line
    }

    /// The item's full path, for example `umbra_math::vector::add`.
    #[must_use]
    pub fn item(&self) -> &str {
        &self.item
    }

    /// What its doc comment lacks.
    #[must_use]
    pub fn missing(&self) -> Missing {
        self.missing
    }
}

/// An item that cites the book: one entry of the book map.
#[derive(Debug)]
pub struct Citation {
    item: String,
    path: PathBuf,
    sections: Vec<citation::Section>,
    symbols: Vec<String>,
}

impl Citation {
    /// The item's line in the book map.
    fn entry(&self) -> String {
        let symbols = self
            .symbols
            .iter()
            .map(|symbol| format!("`{symbol}`"))
            .collect::<Vec<_>>();
        let path = self.path.display();
        format!(
            "- `{}`: pbrt-v4 {} in [{path}](../{path})\n",
            self.item,
            symbols.join(", ")
        )
    }
}

/// The top of `docs/book-map.md`.
const BOOK_MAP_HEADER: &str = "# Book map

<!-- Generated by `cargo xtask book-map`: do not edit. -->

Where each section of _Physically Based Rendering_, 4th edition, is implemented in the rendering core (QS-4).
";

/// The outcome of checking the core crates.
#[derive(Debug, Default)]
pub struct Audit {
    violations: Vec<Violation>,
    citations: Vec<Citation>,
}

impl Audit {
    /// The items that must cite the book but do not.
    #[must_use]
    pub fn violations(&self) -> &[Violation] {
        &self.violations
    }

    /// Checks the items of one source file.
    fn add(&mut self, source: &Source) -> syn::Result<()> {
        let file = syn::parse_file(&source.text)?;
        Walker {
            path: &source.path,
            audit: self,
        }
        .items(&source.module, &file.items);
        Ok(())
    }

    /// `docs/book-map.md`: every cited section in book order, with the items
    /// that implement it.
    #[must_use]
    pub fn book_map(&self) -> String {
        let mut by_section = BTreeMap::<&citation::Section, Vec<&Citation>>::new();
        let entries = self.citations.iter().flat_map(|citation| {
            citation
                .sections
                .iter()
                .map(move |section| (section, citation))
        });
        for (section, citation) in entries {
            by_section.entry(section).or_default().push(citation);
        }
        let mut map = String::from(BOOK_MAP_HEADER);
        if by_section.is_empty() {
            map.push_str("\nNo rendering-core item cites the book yet.\n");
        }
        let sections = by_section.into_iter().map(|(section, mut citations)| {
            citations.sort_by(|a, b| a.item.cmp(&b.item));
            let lines: String = citations.iter().map(|citation| citation.entry()).collect();
            format!("\n## {section}\n\n{lines}")
        });
        map.extend(sections);
        map
    }
}

/// Checks every item of `sources` against the citation rule.
///
/// Every item that is not private, and every method of such a trait, must
/// cite a book section and a pbrt-v4 symbol in its doc comment, or declare
/// `Not in pbrt-v4: <reason>`. Methods of trait impls, private items and
/// `#[cfg(test)]` modules are exempt.
///
/// # Errors
///
/// A source that is not valid Rust.
pub fn audit(sources: &[Source]) -> syn::Result<Audit> {
    let mut audit = Audit::default();
    for source in sources {
        audit.add(source)?;
    }
    Ok(audit)
}

/// Checks the core crates of the repository at `root` (see [`audit`]).
///
/// # Errors
///
/// A core crate's sources cannot be read or are not valid Rust.
pub fn audit_workspace(root: &Path) -> Result<Audit, Error> {
    let mut audit = Audit::default();
    for source in &workspace::core_sources(root)? {
        audit
            .add(source)
            .map_err(|e| Error::Parse(source.path.clone(), e))?;
    }
    Ok(audit)
}

/// Visits the items of one source file, recording what [`audit`] finds.
struct Walker<'a> {
    path: &'a Path,
    audit: &'a mut Audit,
}

impl Walker<'_> {
    fn items(&mut self, module: &str, items: &[syn::Item]) {
        for item in items {
            self.item(module, item);
        }
    }

    fn item(&mut self, module: &str, item: &syn::Item) {
        use syn::Item;
        match item {
            Item::Fn(it) => self.public(module, &it.vis, &it.attrs, &it.sig.ident),
            Item::Struct(it) => self.public(module, &it.vis, &it.attrs, &it.ident),
            Item::Enum(it) => self.public(module, &it.vis, &it.attrs, &it.ident),
            Item::Union(it) => self.public(module, &it.vis, &it.attrs, &it.ident),
            Item::Type(it) => self.public(module, &it.vis, &it.attrs, &it.ident),
            Item::Const(it) => self.public(module, &it.vis, &it.attrs, &it.ident),
            Item::Static(it) => self.public(module, &it.vis, &it.attrs, &it.ident),
            Item::Trait(it) => self.trait_(module, it),
            Item::Impl(it) => self.impl_(module, it),
            Item::Mod(it) => self.module(module, it),
            // Re-exports, macros and foreign items define nothing to cite;
            // `syn::Item` is `#[non_exhaustive]`.
            Item::ExternCrate(_)
            | Item::ForeignMod(_)
            | Item::Macro(_)
            | Item::TraitAlias(_)
            | Item::Use(_)
            | Item::Verbatim(_)
            | _ => {}
        }
    }

    fn trait_(&mut self, module: &str, item: &syn::ItemTrait) {
        if is_private(&item.vis) {
            return;
        }
        self.check(module, &item.attrs, &item.ident);
        let owner = format!("{module}::{}", item.ident);
        for method in item.items.iter().filter_map(trait_method) {
            self.check(&owner, &method.attrs, &method.sig.ident);
        }
    }

    /// Inherent methods only: a trait impl's methods are cited by the trait
    /// or the type.
    fn impl_(&mut self, module: &str, item: &syn::ItemImpl) {
        if item.trait_.is_some() {
            return;
        }
        let owner = format!("{module}::{}", type_name(&item.self_ty));
        for method in item.items.iter().filter_map(impl_method) {
            self.public(&owner, &method.vis, &method.attrs, &method.sig.ident);
        }
    }

    fn module(&mut self, module: &str, item: &syn::ItemMod) {
        if is_cfg_test(&item.attrs) {
            return;
        }
        if let Some((_, items)) = &item.content {
            self.items(&format!("{module}::{}", item.ident), items);
        }
    }

    fn public(
        &mut self,
        owner: &str,
        vis: &syn::Visibility,
        attrs: &[syn::Attribute],
        ident: &syn::Ident,
    ) {
        if !is_private(vis) {
            self.check(owner, attrs, ident);
        }
    }

    fn check(&mut self, owner: &str, attrs: &[syn::Attribute], ident: &syn::Ident) {
        let item = format!("{owner}::{ident}");
        let missing = match Reference::parse(&doc(attrs)) {
            Reference::Cited { sections, symbols } => {
                let path = self.path.to_owned();
                self.audit.citations.push(Citation {
                    item,
                    path,
                    sections,
                    symbols,
                });
                return;
            }
            Reference::NotInPbrt => return,
            Reference::MissingSection => Missing::Section,
            Reference::MissingSymbol => Missing::Symbol,
            Reference::MissingBoth => Missing::SectionAndSymbol,
        };
        let path = self.path.to_owned();
        let line = ident.span().start().line;
        self.audit.violations.push(Violation {
            path,
            line,
            item,
            missing,
        });
    }
}

fn trait_method(item: &syn::TraitItem) -> Option<&syn::TraitItemFn> {
    let syn::TraitItem::Fn(method) = item else {
        return None;
    };
    Some(method)
}

fn impl_method(item: &syn::ImplItem) -> Option<&syn::ImplItemFn> {
    let syn::ImplItem::Fn(method) = item else {
        return None;
    };
    Some(method)
}

fn is_private(vis: &syn::Visibility) -> bool {
    matches!(vis, syn::Visibility::Inherited)
}

/// True for `#[cfg(test)]`.
fn is_cfg_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|attr| match &attr.meta {
        syn::Meta::List(list) => list.path.is_ident("cfg") && list.tokens.to_string() == "test",
        syn::Meta::Path(_) | syn::Meta::NameValue(_) => false,
    })
}

/// The name of an impl's self type: the last segment of its path.
fn type_name(ty: &syn::Type) -> String {
    let segment = if let syn::Type::Path(path) = ty {
        path.path.segments.last()
    } else {
        None
    };
    segment.map_or_else(
        || String::from("<type>"),
        |segment| segment.ident.to_string(),
    )
}

/// The doc comment carried by `attrs`, one line per `///` line.
fn doc(attrs: &[syn::Attribute]) -> String {
    attrs
        .iter()
        .filter(|attr| attr.path().is_ident("doc"))
        .filter_map(|attr| match &attr.meta {
            syn::Meta::NameValue(syn::MetaNameValue {
                value:
                    syn::Expr::Lit(syn::ExprLit {
                        lit: syn::Lit::Str(text),
                        ..
                    }),
                ..
            }) => Some(text.value()),
            syn::Meta::NameValue(_) | syn::Meta::Path(_) | syn::Meta::List(_) => None,
        })
        .collect::<Vec<_>>()
        .join("\n")
}
