//! The citation rule and the book map, on in-memory core-crate sources.

use xtask::{Audit, Missing, Source};

fn audit(text: &str) -> Audit {
    let source = Source::new(
        "crates/umbra-math/src/vector.rs",
        "umbra_math::vector",
        text,
    );
    xtask::audit(&[source]).expect("the fixture parses")
}

fn missing(audit: &Audit) -> Vec<(&str, Missing)> {
    audit
        .violations()
        .iter()
        .map(|violation| (violation.item(), violation.missing()))
        .collect()
}

#[test]
fn an_uncited_public_function_is_rejected() {
    let audit = audit("/// Adds two vectors.\npub fn add() {}\n");

    assert_eq!(
        missing(&audit),
        [("umbra_math::vector::add", Missing::SectionAndSymbol)]
    );
}

#[test]
fn a_function_citing_section_and_symbol_is_accepted() {
    let audit = audit(
        "/// Squared length.\n///\n/// PBR 4e §3.3.2, pbrt-v4 `LengthSquared`.\npub fn length_squared() {}\n",
    );

    assert_eq!(missing(&audit), []);
}

#[test]
fn a_citation_needs_both_the_section_and_the_symbol() {
    let audit = audit(
        "/// PBR 4e §3.3.2.\npub fn only_section() {}\n/// pbrt-v4 `Dot`.\npub fn only_symbol() {}\n",
    );

    assert_eq!(
        missing(&audit),
        [
            ("umbra_math::vector::only_section", Missing::Symbol),
            ("umbra_math::vector::only_symbol", Missing::Section),
        ]
    );
}

#[test]
fn an_item_outside_pbrt_v4_opts_out_with_a_reason() {
    let audit = audit(
        "/// Not in pbrt-v4: closed-enum dispatch (ADR 0006).\npub fn with_reason() {}\n\
        /// Not in pbrt-v4:\npub fn without_reason() {}\n",
    );

    assert_eq!(
        missing(&audit),
        [(
            "umbra_math::vector::without_reason",
            Missing::SectionAndSymbol
        )]
    );
}

#[test]
fn private_items_need_no_citation() {
    let audit = audit("fn helper() {}\nstruct Scratch;\n");

    assert_eq!(missing(&audit), []);
}

#[test]
fn every_kind_of_public_item_needs_a_citation() {
    let audit = audit(
        "pub struct Vector3;\npub enum Axis { X }\npub union Bits { f: f32 }\npub type Vector3f = Vector3;\n\
        pub const ZERO: Vector3 = Vector3;\npub static ONE: Vector3 = Vector3;\npub(crate) trait Tuple {}\n",
    );

    assert_eq!(
        missing(&audit),
        [
            ("umbra_math::vector::Vector3", Missing::SectionAndSymbol),
            ("umbra_math::vector::Axis", Missing::SectionAndSymbol),
            ("umbra_math::vector::Bits", Missing::SectionAndSymbol),
            ("umbra_math::vector::Vector3f", Missing::SectionAndSymbol),
            ("umbra_math::vector::ZERO", Missing::SectionAndSymbol),
            ("umbra_math::vector::ONE", Missing::SectionAndSymbol),
            ("umbra_math::vector::Tuple", Missing::SectionAndSymbol),
        ]
    );
}

#[test]
fn methods_are_checked_as_type_and_name() {
    let audit = audit(
        "/// Not in pbrt-v4: test.\npub struct Vector3;\n\
        impl Vector3 {\n    pub fn dot(&self) {}\n    fn helper(&self) {}\n}\n\
        impl Default for Vector3 {\n    fn default() -> Self { Vector3 }\n}\n",
    );

    assert_eq!(
        missing(&audit),
        [(
            "umbra_math::vector::Vector3::dot",
            Missing::SectionAndSymbol
        )]
    );
}

#[test]
fn trait_methods_are_checked_with_their_trait() {
    let audit = audit(
        "/// Not in pbrt-v4: test.\npub trait Shape {\n    fn intersect(&self);\n}\n\
        trait Private {\n    fn hidden(&self);\n}\n",
    );

    assert_eq!(
        missing(&audit),
        [(
            "umbra_math::vector::Shape::intersect",
            Missing::SectionAndSymbol
        )]
    );
}

#[test]
fn inline_modules_extend_the_path_and_test_modules_are_skipped() {
    let audit = audit(
        "mod simd {\n    pub fn lanes() {}\n}\n\
        #[cfg(test)]\nmod tests {\n    pub fn fixture() {}\n}\n",
    );

    assert_eq!(
        missing(&audit),
        [("umbra_math::vector::simd::lanes", Missing::SectionAndSymbol)]
    );
}

#[test]
fn the_book_map_lists_each_section_in_book_order() {
    let audit = audit(
        "/// PBR 4e §B.2.1, pbrt-v4 `Transform`.\npub struct Transform;\n\
        /// PBR 4e §10.2 and PBR 4e §3.3.2, pbrt-v4 `Normalize`.\npub fn normalize() {}\n\
        /// PBR 4e §3.3.2, pbrt-v4 `Dot`, pbrt-v4 `AbsDot`.\npub fn dot() {}\n",
    );

    assert_eq!(
        audit.book_map(),
        "# Book map\n\
        \n\
        <!-- Generated by `cargo xtask book-map`: do not edit. -->\n\
        \n\
        Where each section of _Physically Based Rendering_, 4th edition, is implemented in the rendering core (QS-4).\n\
        \n\
        ## §3.3.2\n\
        \n\
        - `umbra_math::vector::dot`: pbrt-v4 `Dot`, `AbsDot` in [crates/umbra-math/src/vector.rs](../crates/umbra-math/src/vector.rs)\n\
        - `umbra_math::vector::normalize`: pbrt-v4 `Normalize` in [crates/umbra-math/src/vector.rs](../crates/umbra-math/src/vector.rs)\n\
        \n\
        ## §10.2\n\
        \n\
        - `umbra_math::vector::normalize`: pbrt-v4 `Normalize` in [crates/umbra-math/src/vector.rs](../crates/umbra-math/src/vector.rs)\n\
        \n\
        ## §B.2.1\n\
        \n\
        - `umbra_math::vector::Transform`: pbrt-v4 `Transform` in [crates/umbra-math/src/vector.rs](../crates/umbra-math/src/vector.rs)\n"
    );
}

#[test]
fn an_empty_book_map_says_so() {
    let audit = audit("fn helper() {}\n");

    assert!(
        audit
            .book_map()
            .ends_with("(QS-4).\n\nNo rendering-core item cites the book yet.\n"),
        "{}",
        audit.book_map()
    );
}
